/* Meaningful offline interaction checks. Same browser setup as render_templates.cjs. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

async function main() {
  const root = path.resolve(__dirname, '../assets/templates');
  const templates = JSON.parse(fs.readFileSync(path.join(root, 'catalog.json'), 'utf8')).templates;
  const browser = await chromium.launch({ headless: true,
    ...(process.env.ADMIN_BROWSER_EXECUTABLE ? { executablePath: process.env.ADMIN_BROWSER_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
  const errors = [], external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', request => { if (/^https?:/.test(request.url())) external.push(request.url()); });
  const url = id => pathToFileURL(path.join(root, id, 'index.html')).href;
  try {
    for (const t of templates) {
      await page.goto(`${url(t.id)}#orders`);
      await page.locator('#order-search').fill('青禾');
      assert.equal(await page.locator('#orders-body tr').count(), 2, `${t.id}: customer search`);
      await page.locator('#order-search').fill('');
      await page.locator('#order-status').selectOption('已完成');
      assert.equal(await page.locator('#orders-body tr').count(), 6, `${t.id}: status filter`);
      const statuses = await page.locator('#orders-body .pill').allTextContents();
      assert.ok(statuses.every(s => s === '已完成'));
      await page.goto(`${url(t.id)}#components`);
      assert.equal(await page.locator('.switch').evaluate(el => Math.round(el.getBoundingClientRect().width)), 38, `${t.id}: switch remains a switch`);
      await page.locator('#volume').focus();
      await page.keyboard.press('ArrowRight');
      assert.equal(await page.locator('#volume-value').textContent(), '66%');
    }
    const base = url('business-blue');
    await page.goto(`${base}#orders`);
    assert.equal(await page.locator('#orders-body tr').count(), 6);
    await page.locator('#sort-amount').click();
    const ascending = await page.locator('#orders-body td:nth-child(4)').allTextContents();
    const amounts = ascending.map(text => Number(text.replace(/[^\d]/g, '')));
    assert.deepEqual(amounts, [...amounts].sort((a,b)=>a-b));
    await page.locator('#select-all').check();
    assert.equal(await page.locator('#selection-count').textContent(), '已选 6 项');
    await page.locator('#next-page').click();
    assert.equal(await page.locator('#page-number').textContent(), '2 / 3');
    assert.equal(await page.locator('#selection-count').textContent(), '已选 6 项');
    const opener = page.locator('#orders-body button[data-order]').first();
    await opener.click();
    assert.equal(await page.locator('#drawer').evaluate(el=>el.open), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#drawer').evaluate(el=>el.open), false);
    assert.equal(await opener.evaluate(el=>document.activeElement===el), true);
    await page.locator('#order-search').fill('不存在的客户');
    assert.match(await page.locator('#orders-body').textContent(), /没有找到/);
    assert.equal(await page.locator('#next-page').isDisabled(), true);
    await page.goto(`${base}#overview`);
    const before = await page.locator('#revenue-chart polyline.series').getAttribute('points');
    await page.locator('#period').selectOption('month');
    assert.notEqual(await page.locator('#revenue-chart polyline.series').getAttribute('points'), before);
    const downloadPromise = page.waitForEvent('download');
    await page.locator('[data-action=export]').click();
    const download = await downloadPromise;
    assert.match(download.suggestedFilename(), /demo-orders\.csv$/);
    await page.goto(`${base}#components`);
    await page.locator('#budget-min').focus();
    await page.keyboard.press('End');
    assert.equal(await page.locator('#budget-min').inputValue(), '800');
    await page.locator('#budget-max').focus();
    await page.keyboard.press('Home');
    assert.equal(await page.locator('#budget-max').inputValue(), '800');
    assert.equal(await page.locator('#budget-value').textContent(), '¥800 — ¥800');
    await page.locator('#split-handle').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#split-handle').getAttribute('aria-valuenow'), '44');
    const handle = await page.locator('#split-handle').boundingBox();
    await page.mouse.move(handle.x + handle.width/2, handle.y + handle.height/2);
    await page.mouse.down();
    await page.mouse.move(handle.x + 45, handle.y + handle.height/2);
    await page.mouse.up();
    assert.ok(Number(await page.locator('#split-handle').getAttribute('aria-valuenow')) > 44);
    await page.locator('.scroll-demo').focus();
    await page.keyboard.press('End');
    await page.waitForFunction(()=>document.querySelector('.scroll-demo').scrollTop>0);
    await page.locator('[data-slide="1"]').click();
    assert.ok(await page.locator('#carousel').evaluate(el=>el.scrollLeft>0));
    await page.locator('#tab-controls').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#tab-feedback').getAttribute('aria-selected'), 'true');
    assert.equal(await page.locator('#feedback-panel').isVisible(), true);
    await page.locator('#dropdown-trigger').click();
    assert.equal(await page.locator('#dropdown-menu').isVisible(), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#dropdown-menu').isVisible(), false);
    await page.locator('#feedback-panel [data-action=confirm]').first().click();
    await page.locator('[data-action=confirm-demo]').click();
    assert.match(await page.locator('#toast').textContent(), /没有修改实际数据/);
    await page.goto(`${base}#settings`);
    await page.locator('[name=workspace]').fill('');
    await page.locator('#settings-form button[type=submit]').click();
    assert.equal(await page.locator('[name=workspace]').evaluate(el=>el.validity.valueMissing), true);
    await page.locator('[name=workspace]').fill('验证工作区');
    await page.locator('#settings-form button[type=submit]').click();
    assert.match(await page.locator('#toast').textContent(), /保存/);
    await page.reload();
    assert.equal(await page.locator('[name=workspace]').inputValue(), '验证工作区');
    await page.locator('#settings-form button[type=reset]').click();
    assert.equal(await page.locator('[name=workspace]').inputValue(), '青禾工作区');
    await page.goto(pathToFileURL(path.join(root, 'gallery.html')).href);
    assert.equal(await page.locator('.template-card').count(), 6);
    await page.locator('#mode').selectOption('dark');
    assert.equal(await page.locator('.template-card').count(), 1);
    await page.locator('[data-id=dark-ops]').click();
    assert.match(await page.locator('#selection-text').inputValue(), /dark-ops/);
    assert.match(await page.locator('#selection-text').inputValue(), /等我确认/);
    await page.locator('#mode').selectOption('all');
    await page.locator('#search').fill('财务');
    assert.equal(await page.locator('.template-card').count(), 1);
    assert.match(await page.locator('.template-card h3').textContent(), /靛蓝/);
    assert.deepEqual(errors, []);
    assert.deepEqual(external, [], 'Templates must remain offline');
    console.log('PASS: all six themes + filtering, sorting, pagination, selection, drawer, charts, CSV export, sliders, resize, scroll, tabs, dialog, dropdown, form persistence and gallery choice');
  } finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
